#!/usr/bin/env python3
"""Generate src/app/v2/lib/snapshot-files.ts — daftar file snapshot per slug
dari public/misi/*/ dan public/proyek/*/. Dipakai Workspace untuk mengubah
rujukan `file.csv` di teks tugas menjadi tautan unduh/lihat langsung.
Jalankan ulang setiap kali snapshot berubah."""
import json, os
ROOT = os.path.join(os.path.dirname(__file__), "..")
manifest = {}
for base in ("misi", "proyek"):
    d = os.path.join(ROOT, "public", base)
    if not os.path.isdir(d):
        continue
    for slug in sorted(os.listdir(d)):
        sd = os.path.join(d, slug)
        if os.path.isdir(sd):
            manifest[slug] = sorted(os.listdir(sd))
out = os.path.join(ROOT, "src/app/v2/lib/snapshot-files.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("/* GENERATED by scripts/gen_snapshot_manifest.py — jangan edit manual.\n")
    f.write("   Daftar file snapshot per slug (public/misi + public/proyek). */\n")
    f.write("export const SNAPSHOT_FILES: Record<string, string[]> = ")
    f.write(json.dumps(manifest, indent=1, ensure_ascii=False))
    f.write(";\n")
print(f"wrote {out}: {len(manifest)} slugs, {sum(len(v) for v in manifest.values())} files")
