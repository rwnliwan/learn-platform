#!/usr/bin/env python3
"""Build-time: convert content/*.md to src/lib/chapters.ts (edge-compatible)."""
import os, json, re

CONTENT_DIR = os.path.join(os.path.dirname(__file__), "../content")
OUT = os.path.join(os.path.dirname(__file__), "../src/lib/chapters.ts")

def _nat_key(s):
    import re as _re
    return [int(x) if x.isdigit() else x for x in _re.split(r"(\d+)", s)]

chapters = []
for f in sorted(os.listdir(CONTENT_DIR), key=_nat_key):
    if not f.endswith(".md"):
        continue
    slug = f[:-3]
    with open(os.path.join(CONTENT_DIR, f), encoding="utf-8") as fh:
        raw = fh.read()
    title = slug
    for line in raw.split("\n"):
        if line.startswith("# "):
            title = line[2:].strip()
            break
    chapters.append({"slug": slug, "title": title, "content": raw})

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// AUTO-GENERATED by scripts/build-content.py — do not edit\n")
    fh.write("export interface Chapter { slug: string; title: string; content: string }\n\n")
    fh.write("export const chapters: Chapter[] = ")
    fh.write(json.dumps(chapters, ensure_ascii=False, indent=2))
    fh.write(";\n")

print(f"Wrote {len(chapters)} chapters to {OUT}")
