#!/usr/bin/env python3
"""Build-time: convert content/*.md to src/lib/chapters.ts (edge-compatible)."""
import os, json, re

CONTENT_DIR = os.path.join(os.path.dirname(__file__), "../content")
OUT = os.path.join(os.path.dirname(__file__), "../src/lib/chapters.ts")

def _nat_key(s):
    import re as _re
    return [int(x) if x.isdigit() else x for x in _re.split(r"(\d+)", s)]

chapters = []
for f in sorted(os.listdir(CONTENT_DIR), key=_nat_key):
    if not f.endswith(".md"):
        continue
    slug = f[:-3]
    with open(os.path.join(CONTENT_DIR, f), encoding="utf-8") as fh:
        raw = fh.read()
    title = slug
    for line in raw.split("\n"):
        if line.startswith("# "):
            title = line[2:].strip()
            break
    chapters.append({"slug": slug, "title": title, "content": raw})

# MERGE (2026-11-12): chapters.ts feeds the legacy /learn/[slug] route.
# content/*.md is no longer the full lesson set — 103 chapters (36 pm-*
# + 67 others) have no .md anymore but are still served live (HTTP 200).
# A plain overwrite would 404 those live URLs, so preserve any existing
# entry whose slug is absent from the regenerated set. New .md content
# always wins on slug collision.
_new_slugs = {c["slug"] for c in chapters}
if os.path.exists(OUT):
    with open(OUT, encoding="utf-8") as fh:
        _old_text = fh.read()
    try:
        # NOTE: "Chapter[]" also contains "[" — anchor on "= [" instead.
        _start = _old_text.index("= [") + 2
        _arr = _old_text[_start:]
        # Tolerate a trailing comma before the closing bracket (HEAD's
        # file has one after the last entry). Content strings never hold
        # a literal newline, so ",\s*]$" at the very end is structural.
        _arr = re.sub(r",\s*\]\s*;\s*$", "]", _arr)
        _old, _ = json.JSONDecoder().raw_decode(_arr)
        _kept = [c for c in _old if c.get("slug") not in _new_slugs]
        chapters.extend(_kept)
        print(f"Preserved {len(_kept)} legacy chapters without .md")
    except (ValueError, IndexError, AttributeError) as e:
        print(f"WARNING: could not parse existing {OUT} ({e}) — overwrite only")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// AUTO-GENERATED by scripts/build-content.py — do not edit\n")
    fh.write("export interface Chapter { slug: string; title: string; content: string }\n\n")
    fh.write("export const chapters: Chapter[] = ")
    fh.write(json.dumps(chapters, ensure_ascii=False, indent=2))
    fh.write(";\n")

print(f"Wrote {len(chapters)} chapters to {OUT}")
